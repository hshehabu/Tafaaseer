// Generates the Android launcher icon (concept A, "open mushaf", chosen 25 Nov 2026;
// drafts in docs/icons/index.html) from one set of shapes:
//
// - res/drawable/ic_launcher_background.xml, ic_launcher_foreground.xml and
//   ic_launcher_monochrome.xml, plus res/mipmap-anydpi-v26/ic_launcher.xml:
//   the adaptive icon (Android 8+) and the themed icon (Android 13+);
// - res/mipmap-*/ic_launcher.png: the icon for Android 7 (minSdk 24);
// - store/play_store_icon.png: the 512 px Play Store icon.
//
// Run from app/:  flutter test tool/app_icon/generate_app_icon_test.dart
// It lives outside test/ so `flutter test` doesn't run it every time.
import 'dart:io';
import 'dart:ui' as ui;

import 'package:flutter/painting.dart';
import 'package:flutter_test/flutter_test.dart';

// Colours from the Dusty Green design system.
const _green = Color(0xFF416757);
const _page = Color(0xFFF3F7F5);
const _rosette = Color(0xFFE4ECE7);

/// One shape of the drawing, in a 512 x 512 space.
sealed class _Shape {
  const _Shape(this.color);
  final Color color;
}

/// A stroked outline: an SVG-style path made of M, L, C and Z commands.
class _Stroke extends _Shape {
  const _Stroke(this.commands, this.width, super.color);
  final List<(String, List<double>)> commands;
  final double width;
}

class _Circle extends _Shape {
  const _Circle(this.cx, this.cy, this.r, super.color, {this.strokeWidth});
  final double cx, cy, r;

  /// Null for a filled dot.
  final double? strokeWidth;
}

/// The open mushaf with the end-of-ayah rosette above it.
const _shapes = <_Shape>[
  _Stroke([
    ('M', [256, 352]), ('C', [214, 324, 160, 318, 112, 326]), ('L', [112, 214]), //
    ('C', [160, 206, 214, 212, 256, 240]), ('Z', []),
  ], 18, _page),
  _Stroke([
    ('M', [256, 352]), ('C', [298, 324, 352, 318, 400, 326]), ('L', [400, 214]), //
    ('C', [352, 206, 298, 212, 256, 240]), ('Z', []),
  ], 18, _page),
  _Stroke([('M', [256, 240]), ('L', [256, 352])], 18, _page),
  _Circle(256, 152, 34, _rosette, strokeWidth: 12),
  _Circle(256, 104, 8, _rosette), _Circle(256, 200, 8, _rosette),
  _Circle(208, 152, 8, _rosette), _Circle(304, 152, 8, _rosette),
  _Circle(290, 118, 6, _rosette), _Circle(222, 118, 6, _rosette),
  _Circle(290, 186, 6, _rosette), _Circle(222, 186, 6, _rosette),
];

/// The drawing's bounds are y 96..361, centred on y 228.5; the icon centre is 256.
const _contentOffsetY = 256 - 228.5;

String _hex(Color c) =>
    '#${(c.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

String _num(double v) => v == v.roundToDouble() ? v.toInt().toString() : v.toStringAsFixed(2);

String _pathData(_Shape s) => switch (s) {
  _Stroke(:final commands) => commands.map((c) => '${c.$1}${c.$2.map(_num).join(',')}').join(' '),
  // A circle as two arcs.
  _Circle(:final cx, :final cy, :final r) =>
    'M${_num(cx - r)},${_num(cy)} a${_num(r)},${_num(r)} 0 1,0 ${_num(2 * r)},0 '
        'a${_num(r)},${_num(r)} 0 1,0 ${_num(-2 * r)},0',
};

String _vectorPath(_Shape s, {Color? override}) {
  final color = _hex(override ?? s.color);
  final data = _pathData(s);
  return switch (s) {
    _Circle(strokeWidth: null) => '    <path android:fillColor="$color" android:pathData="$data"/>',
    _Circle(:final strokeWidth) =>
      '    <path android:strokeColor="$color" android:strokeWidth="${_num(strokeWidth!)}" android:pathData="$data"/>',
    _Stroke(:final width) =>
      '    <path android:strokeColor="$color" android:strokeWidth="${_num(width)}" '
          'android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="$data"/>',
  };
}

/// The adaptive foreground: a 108 dp canvas whose middle 66 dp circle is always
/// visible, whatever mask the launcher uses. The drawing (about 405 units
/// corner to corner) is scaled by 0.74 to about 300, inside the safe circle's
/// 313 units (66 / 108 of 512).
String _foregroundXml({Color? color}) {
  const scale = 0.74;
  return '''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icon/generate_app_icon_test.dart; edit that file, not this one. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="512" android:viewportHeight="512">
  <group android:pivotX="256" android:pivotY="256"
      android:scaleX="$scale" android:scaleY="$scale"
      android:translateY="${_num(_contentOffsetY * scale)}">
${_shapes.map((s) => _vectorPath(s, override: color)).join('\n')}
  </group>
</vector>
''';
}

const _backgroundXml = '''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icon/generate_app_icon_test.dart; edit that file, not this one. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
  <path android:fillColor="#416757" android:pathData="M0,0h108v108h-108z"/>
</vector>
''';

const _adaptiveXml = '''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icon/generate_app_icon_test.dart; edit that file, not this one. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@drawable/ic_launcher_background"/>
  <foreground android:drawable="@drawable/ic_launcher_foreground"/>
  <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
''';

/// Draws the icon on a [size] square: a rounded green tile for launchers, or a
/// full square for the Play Store (which applies its own mask).
Future<List<int>> _png(int size, {required bool rounded}) async {
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder)..scale(size / 512);
  final tile = Paint()..color = _green;
  if (rounded) {
    canvas.drawRRect(RRect.fromRectAndRadius(const Rect.fromLTWH(0, 0, 512, 512), const Radius.circular(112)), tile);
  } else {
    canvas.drawRect(const Rect.fromLTWH(0, 0, 512, 512), tile);
  }
  canvas.translate(0, _contentOffsetY);
  for (final s in _shapes) {
    final paint = Paint()
      ..color = s.color
      ..isAntiAlias = true;
    switch (s) {
      case _Circle(:final cx, :final cy, :final r, :final strokeWidth):
        if (strokeWidth != null) {
          paint
            ..style = PaintingStyle.stroke
            ..strokeWidth = strokeWidth;
        }
        canvas.drawCircle(Offset(cx, cy), r, paint);
      case _Stroke(:final commands, :final width):
        final path = Path();
        for (final (op, v) in commands) {
          switch (op) {
            case 'M':
              path.moveTo(v[0], v[1]);
            case 'L':
              path.lineTo(v[0], v[1]);
            case 'C':
              path.cubicTo(v[0], v[1], v[2], v[3], v[4], v[5]);
            case 'Z':
              path.close();
          }
        }
        canvas.drawPath(
          path,
          paint
            ..style = PaintingStyle.stroke
            ..strokeWidth = width
            ..strokeCap = StrokeCap.round
            ..strokeJoin = StrokeJoin.round,
        );
    }
  }
  final image = await recorder.endRecording().toImage(size, size);
  final bytes = await image.toByteData(format: ui.ImageByteFormat.png);
  return bytes!.buffer.asUint8List();
}

void main() {
  test('generate the app icon', () async {
    const res = 'android/app/src/main/res';
    File('$res/drawable/ic_launcher_background.xml').writeAsStringSync(_backgroundXml.trimLeft());
    File('$res/drawable/ic_launcher_foreground.xml').writeAsStringSync(_foregroundXml().trimLeft());
    // Themed icons: Android tints this one-colour layer to match the wallpaper.
    File('$res/drawable/ic_launcher_monochrome.xml')
        .writeAsStringSync(_foregroundXml(color: const Color(0xFFFFFFFF)).trimLeft());
    Directory('$res/mipmap-anydpi-v26').createSync(recursive: true);
    File('$res/mipmap-anydpi-v26/ic_launcher.xml').writeAsStringSync(_adaptiveXml.trimLeft());

    const densities = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192};
    for (final MapEntry(key: density, value: size) in densities.entries) {
      File('$res/mipmap-$density/ic_launcher.png').writeAsBytesSync(await _png(size, rounded: true));
    }
    Directory('store').createSync();
    File('store/play_store_icon.png').writeAsBytesSync(await _png(512, rounded: false));
  });
}
